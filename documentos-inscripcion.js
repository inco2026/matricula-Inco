export function claveDocumento(texto) {
 const t=String(texto||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase();
 if(t.includes('fotograf'))return 'fotografias';
 if(t.includes('dui'))return 'dui';
 if(t.includes('hoja de inscrip'))return 'hoja';
 if(t.includes('partida de nacimiento'))return 'partida';
 if(t.includes('conducta'))return 'conducta';
 if(t.includes('social'))return 'servicio-social';
 if(t.includes('siges'))return 'boleta-siges';
 if(t.includes('certificado') || t.includes('boleta'))return 'certificados';
 return t;
}
